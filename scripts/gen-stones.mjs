// Safe to edit by hand
// Writes the Home board's generated stone art (board E, 2026-10-17). Run with `npm run gen:stones`
// after changing a seed, a size or a colour in scripts/lib/stone-mosaic.mjs; the output is
// committed, so the site build never runs the (slow, about 10 s) generators.
//
//   src/components/home/stones.generated.ts   the wide and phone stone paths, the 4 markers
//   public/textures/tile-{sky,green,deep}.svg the mosaic texture tiles for the bands and card
//
// Seeds and sizes are the ones board E was approved with (the wide path is seed 7 at 1440x320,
// the phone path seed 11 at 390x180; tiles 3, 5 and 7 at 420). `--check` regenerates in memory
// and exits 1 if a committed file differs, without writing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mosaicTile, stoneMarkers, stonePath, MARKER_RUNS } from './lib/stone-mosaic.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

export const PATHS = {
  wide: { width: 1440, height: 320, preset: 'wide', seed: 7 },
  phone: { width: 390, height: 180, preset: 'phone', seed: 11 },
};

export const TILES = {
  sky: {
    size: 420,
    grout: '#FFFFFF',
    fills: ['#E8F1FA', '#EAF2FB', '#E5EFF9', '#EDF4FC'],
    seed: 3,
  },
  green: {
    size: 420,
    grout: '#FFFFFF',
    fills: ['#E9F1EB', '#EBF3ED', '#E6EFE8', '#EEF5F0'],
    seed: 5,
  },
  deep: {
    size: 420,
    grout: '#1E5385',
    fills: ['#235E93', '#24609A', '#225B8E', '#26639B'],
    seed: 7,
  },
};

const outputs = new Map();

const ts = (name, value) => `export const ${name} = ${JSON.stringify(value, null, 0)} as const;\n`;
const wide = stonePath(PATHS.wide);
const phone = stonePath(PATHS.phone);
const markers = stoneMarkers(21).map((ds, i) => ds.map((d, j) => ({ d, fill: MARKER_RUNS[i][j] })));
outputs.set(
  'src/components/home/stones.generated.ts',
  '// GENERATED by scripts/gen-stones.mjs (npm run gen:stones). Do not edit by hand.\n' +
    '// Board E stone art: { d, fill } per stone, in path order (water first, the cross last).\n' +
    `export const PATH_WIDE_VIEWBOX = '0 0 ${PATHS.wide.width} ${PATHS.wide.height}';\n` +
    `export const PATH_PHONE_VIEWBOX = '0 0 ${PATHS.phone.width} ${PATHS.phone.height}';\n` +
    ts('PATH_WIDE', wide) +
    ts('PATH_PHONE', phone) +
    '/** Section markers in page order: sky, green, gold, red. viewBox 0 0 78 36. */\n' +
    ts('MARKERS', markers),
);
for (const [name, opts] of Object.entries(TILES)) {
  outputs.set(`public/textures/tile-${name}.svg`, mosaicTile(opts));
}

let stale = 0;
for (const [rel, body] of outputs) {
  const file = path.join(root, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current !== body) {
      console.log(`STALE ${rel}`);
      stale++;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
  console.log(`wrote ${rel} (${(body.length / 1024).toFixed(0)} KB)`);
}
console.log(`stones: wide ${wide.length}, phone ${phone.length}; markers ${markers.length}`);
if (check && stale) process.exit(1);
