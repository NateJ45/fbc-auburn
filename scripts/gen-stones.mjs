// Safe to edit by hand
// Writes the Home board's generated stone art. Run with `npm run gen:stones` after changing a
// seed, a size or a colour in scripts/lib/stone-mosaic.mjs; the output is committed, so the site
// build never runs the generators.
//
//   src/components/home/stones.generated.ts   the wide and phone stone paths, the section marker
//   src/assets/textures/tile-deep.svg             the This Sunday card's stone ground
//   src/assets/textures/tile-{green,navy,sky}.svg the section library's panels and sermon art
//                                             (church-blocks.css, collections.css)
//   public/studio-banner/stone-path*.svg      the stone path along the Studio Home banner's foot
//                                             (kit.config.ts homeBanner.motif, card 118)
//   public/studio-banner/marker.svg           the three gold steps, as the Studio's section marker
//                                             (brand.config.json studio.look.marker, card 128)
//
// Redrawn 2026-10-21 for the brick brand (docs/design-directions/2026-10-21-brick-path/): every
// piece is now brick courses from scripts/lib/brick-courses.mjs. The wide path is a low wall of
// three courses in a 960x240 box stepping up toward the This Sunday card; the phone path is two
// courses in a 390x96 strip under the card. The 2026-10-17 pebble generators stay in
// scripts/lib/stone-mosaic.mjs, unused. `--check` regenerates in memory and exits 1 if a
// committed file differs, without writing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { BRICK_PATH_PRESETS, brickMarker, brickPath, brickTile } from './lib/brick-courses.mjs';
import { fleckPath, printMask } from './lib/brick-print.mjs';
import { lcg } from './lib/stone-mosaic.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

export const PATHS = {
  wide: { width: 960, height: 240, preset: 'wide', seed: 7 },
  phone: { width: 390, height: 96, preset: 'phone', seed: 11 },
  sill: { width: 1600, height: 64, preset: 'sill', seed: 5 },
  // The Studio Home banner's foot (kit.config.ts homeBanner.motif, card 118).
  banner: { width: 1040, height: 88, preset: 'banner', seed: 4 },
  bannerPhone: { width: 390, height: 56, preset: 'bannerPhone', seed: 2 },
};

export const TILES = {
  deep: {
    size: 420,
    // A grout close to the stones, so the texture stays behind the card's white text (Home critic).
    grout: '#1B3354',
    fills: ['#1F3A5F', '#213D64', '#1D3659', '#23405F'],
    seed: 7,
  },
  // The sermon and series art with no picture (SermonArt.astro, block polish 2026-10-18): three
  // grounds for the book name, picked per series. Grout close to the stones, as above.
  green: {
    size: 420,
    grout: '#274874',
    fills: ['#2C4F7C', '#2E527F', '#2A4B77', '#305581'],
    seed: 13,
  },
  navy: {
    size: 420,
    grout: '#11294A',
    fills: ['#16304D', '#18334F', '#142C47', '#1A3552'],
    seed: 17,
  },
  // A pale warm ground (2026-10-23): Home's "Other ways in" band (home-board.css .hb-band--green),
  // the printed brick in the band's own tint, so its white cards sit on a wall.
  warm: {
    size: 420,
    grout: '#E6D8CE',
    fills: ['#F1E8E2', '#F4ECE6', '#EEE3DC', '#F2E9E3'],
    seed: 23,
  },
  // A pale sky ground: a person with no photo (PersonCard.astro) and the library's quiet panels.
  sky: {
    size: 420,
    grout: '#D3DCE8',
    fills: ['#E6EBF2', '#E9EEF5', '#E1E8F1', '#EDF1F7'],
    seed: 19,
  },
};

const outputs = new Map();

const ts = (name, value) => `export const ${name} = ${JSON.stringify(value, null, 0)} as const;\n`;
const wide = brickPath(PATHS.wide);
const phone = brickPath(PATHS.phone);
const sill = brickPath(PATHS.sill);
const marker = brickMarker();
// The linocut flecks (2026-10-23): one mask per drawing, punched through all its bricks. The id is
// a placeholder: each renderer swaps in its own, since a page can draw the sill twice.
const printDefs = ({ width, height, preset }, seed) =>
  printMask('__ID__', { x: 0, y: 0, w: width, h: height, u: BRICK_PATH_PRESETS[preset].h, seed });
outputs.set(
  'src/components/home/stones.generated.ts',
  '// GENERATED by scripts/gen-stones.mjs (npm run gen:stones). Do not edit by hand.\n' +
    '// Home brick art: { d, fill } per brick, in laying order (bottom course first, left to right).\n' +
    `export const PATH_WIDE_VIEWBOX = '0 0 ${PATHS.wide.width} ${PATHS.wide.height}';\n` +
    `export const PATH_PHONE_VIEWBOX = '0 0 ${PATHS.phone.width} ${PATHS.phone.height}';\n` +
    ts('PATH_WIDE', wide) +
    ts('PATH_PHONE', phone) +
    '/** Fleck masks: swap __ID__ for an id unique in the page and put mask="url(#id)" on the bricks. */\n' +
    ts('PATH_WIDE_PRINT', printDefs(PATHS.wide, 31)) +
    ts('PATH_PHONE_PRINT', printDefs(PATHS.phone, 37)) +
    `export const SILL_VIEWBOX = '0 0 ${PATHS.sill.width} ${PATHS.sill.height}';\n` +
    '/** The sill: the doorstep along the footer and the menu, two courses of brick. */\n' +
    ts('SILL', sill) +
    ts('SILL_PRINT', printDefs(PATHS.sill, 41)) +
    '/** The section marker: three stepped bricks. viewBox 0 0 78 36. */\n' +
    ts('MARKER', marker),
);
const svgOf = ({ width, height }, stones, defs = '') =>
  `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 ${width} ${height}" width="${width}" height="${height}">` +
  defs.replaceAll('__ID__', 'print') +
  (defs ? '<g mask="url(#print)">' : '') +
  stones.map((st) => `<path d="${st.d}" fill="${st.fill}"/>`).join('') +
  (defs ? '</g>' : '') +
  '</svg>\n';
// The auburn bricks read as they are on the navy Home banner, so the banner strips take the
// same deck as the site path.
const banner = brickPath(PATHS.banner);
const bannerPhone = brickPath(PATHS.bannerPhone);
outputs.set(
  'public/studio-banner/stone-path.svg',
  svgOf(PATHS.banner, banner, printDefs(PATHS.banner, 43)),
);
outputs.set(
  'public/studio-banner/stone-path-phone.svg',
  svgOf(PATHS.bannerPhone, bannerPhone, printDefs(PATHS.bannerPhone, 47)),
);
// The Studio's section marker (card 128): the same three stepped bricks as the site's .hb-label.
outputs.set('public/studio-banner/marker.svg', svgOf({ width: 78, height: 36 }, marker));
// The bricks drawn as CSS boxes (the numbered bricks of "Your first Sunday", home-board.css
// .hb-walk__stone, and the 404's steps) take the linocut flecks as a background layer: pale paper
// specks on a transparent ground, drawn at the size of one 64 x 44 brick and sized like the Home
// path's (u 30), so a numeral on top stays clear.
{
  const rnd = lcg(59);
  const d = fleckPath(4, 4, 56, 36, 30, 11, rnd);
  const flecks = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 64 44" width="64" height="44"><path d="${d}" fill="#FBF8F3" fill-opacity="0.9"/></svg>\n`;
  outputs.set('src/assets/textures/print-flecks.svg', flecks);
  // The Studio's numbered steps wear the same print (studio.look.stoneFlecks, PORTS.md card 180).
  outputs.set('public/studio-banner/print-flecks.svg', flecks);
}
for (const [name, opts] of Object.entries(TILES)) {
  outputs.set(`src/assets/textures/tile-${name}.svg`, brickTile(opts));
}

let stale = 0;
for (const [rel, body] of outputs) {
  const file = path.join(root, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current !== body) {
      console.log(`STALE ${rel}`);
      stale++;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
  console.log(`wrote ${rel} (${(body.length / 1024).toFixed(0)} KB)`);
}
console.log(
  `bricks: wide ${wide.length}, phone ${phone.length}, sill ${sill.length}, banner ${banner.length}, banner phone ${bannerPhone.length}; marker ${marker.length}`,
);
if (check && stale) process.exit(1);
