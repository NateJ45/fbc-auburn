// Safe to edit by hand
// Writes the Home board's generated stone art. Run with `npm run gen:stones` after changing a
// seed, a size or a colour in scripts/lib/stone-mosaic.mjs; the output is committed, so the site
// build never runs the generators.
//
//   src/components/home/stones.generated.ts   the wide and phone stone paths, the section marker
//   public/textures/tile-deep.svg             the This Sunday card's stone ground
//
// Redrawn 2026-10-17 after the Home audit: soft, hand-laid stones between the old pebbles and the
// mark's dressed stones, in four clear bands of the mark's colours. The wide path is 960x240 and
// its red end meets the This Sunday card; the phone path is a short 390x96 strip under the
// card. `--check` regenerates in memory and exits 1 if a committed file differs, without writing.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { mosaicTile, stoneMarkers, stonePath } from './lib/stone-mosaic.mjs';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const check = process.argv.includes('--check');

export const PATHS = {
  wide: { width: 960, height: 240, preset: 'wide', seed: 7 },
  phone: { width: 390, height: 96, preset: 'phone', seed: 11 },
  sill: { width: 1600, height: 64, preset: 'sill', seed: 5 },
};

export const TILES = {
  deep: {
    size: 420,
    // A grout close to the stones, so the texture stays behind the card's white text (Home critic).
    grout: '#205890',
    fills: ['#235E93', '#24609A', '#225B8E', '#26639B'],
    seed: 7,
  },
};

const outputs = new Map();

const ts = (name, value) => `export const ${name} = ${JSON.stringify(value, null, 0)} as const;\n`;
const wide = stonePath(PATHS.wide);
const phone = stonePath(PATHS.phone);
const sill = stonePath(PATHS.sill);
const marker = stoneMarkers();
outputs.set(
  'src/components/home/stones.generated.ts',
  '// GENERATED by scripts/gen-stones.mjs (npm run gen:stones). Do not edit by hand.\n' +
    '// Home stone art: { d, fill } per stone, in path order (the water first, the gold steps last).\n' +
    `export const PATH_WIDE_VIEWBOX = '0 0 ${PATHS.wide.width} ${PATHS.wide.height}';\n` +
    `export const PATH_PHONE_VIEWBOX = '0 0 ${PATHS.phone.width} ${PATHS.phone.height}';\n` +
    ts('PATH_WIDE', wide) +
    ts('PATH_PHONE', phone) +
    `export const SILL_VIEWBOX = '0 0 ${PATHS.sill.width} ${PATHS.sill.height}';\n` +
    '/** The sill: the doorstep along the footer and the menu, in the same story colours. */\n' +
    ts('SILL', sill) +
    '/** The section marker: three gold steps. viewBox 0 0 78 36. */\n' +
    ts('MARKER', marker),
);
for (const [name, opts] of Object.entries(TILES)) {
  outputs.set(`public/textures/tile-${name}.svg`, mosaicTile(opts));
}

let stale = 0;
for (const [rel, body] of outputs) {
  const file = path.join(root, rel);
  const current = fs.existsSync(file) ? fs.readFileSync(file, 'utf8') : null;
  if (check) {
    if (current !== body) {
      console.log(`STALE ${rel}`);
      stale++;
    }
    continue;
  }
  fs.mkdirSync(path.dirname(file), { recursive: true });
  fs.writeFileSync(file, body);
  console.log(`wrote ${rel} (${(body.length / 1024).toFixed(0)} KB)`);
}
console.log(
  `stones: wide ${wide.length}, phone ${phone.length}, sill ${sill.length}; marker ${marker.length}`,
);
if (check && stale) process.exit(1);
