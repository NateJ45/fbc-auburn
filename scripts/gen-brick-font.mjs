// Safe to edit by hand
// Bakes the Young Serif outlines the brick letterforms need into scripts/lib/brick-font.generated.mjs
// (2026-10-21), so the generator (scripts/lib/brick-letters.mjs) is pure: no file reads, which
// matters because it also runs inside the Worker for server-rendered routes. Run: npm run gen:letters
//
// Two readers of the same font file, as in scripts/brand-logo.mjs: fontkitten draws the outlines
// (opentype.js writes NaN into a few of this font's CFF glyphs) and opentype.js supplies the
// kerning pairs, which fontkitten does not expose.
//
// Output, all in font units (y up is negative, so the glyph sits on the baseline y = 0):
//   UPM, GLYPHS[char] = [advance, yMin, yMax, d], KERN['AV'] = units.
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import opentype from 'opentype.js';
import { create } from 'fontkitten';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const file = path.join(
  root,
  'node_modules/@fontsource/young-serif/files/young-serif-latin-400-normal.woff',
);
const buf = fs.readFileSync(file);
const outlines = create(buf);
const ot = opentype.parse(buf.buffer.slice(buf.byteOffset, buf.byteOffset + buf.byteLength));

// Printable ASCII and the typographic punctuation a heading can carry.
const chars = [];
for (let c = 32; c <= 126; c++) chars.push(String.fromCodePoint(c));

chars.push(...'‘’“”–—…•·€'.split(''));

const upm = outlines.unitsPerEm;
const GLYPHS = {};
for (const ch of chars) {
  const g = outlines.glyphForCodePoint(ch.codePointAt(0));
  if (!g || (g.id === 0 && ch !== ' ')) continue;
  const p = g.path.scale(1, -1);
  const d = ch === ' ' ? '' : p.toSVG().replace(/(\d+\.\d{2})\d+/g, '$1');
  if (/NaN/.test(d)) throw new Error(`NaN in glyph ${ch}`);
  const b = ch === ' ' ? null : p.bbox;
  GLYPHS[ch] = [
    Math.round(g.advanceWidth),
    b ? Math.round(b.minY) : 0,
    b ? Math.round(b.maxY) : 0,
    d,
  ];
}
const KERN = {};
// Kerning only for ASCII letters and basic punctuation: accents and symbols are rare in headings.
const keys = Object.keys(GLYPHS).filter((c) => /[A-Za-z.,:;!?'’-]/.test(c));
for (const a of keys)
  for (const b of keys) {
    const k = ot.getKerningValue(ot.charToGlyph(a), ot.charToGlyph(b));
    if (k) KERN[a + b] = k;
  }

const out =
  `// GENERATED by scripts/gen-brick-font.mjs (npm run gen:letters). Do not edit by hand.\n` +
  `// Young Serif outlines for the brick letterforms, in font units, y up negative.\n` +
  `export const UPM = ${upm};\n` +
  `export const GLYPHS = ${JSON.stringify(GLYPHS)};\n` +
  `export const KERN = ${JSON.stringify(KERN)};\n`;
fs.writeFileSync(path.join(root, 'scripts/lib/brick-font.generated.mjs'), out);
console.log(
  `glyphs ${Object.keys(GLYPHS).length}, kern pairs ${Object.keys(KERN).length}, ${out.length} bytes`,
);
