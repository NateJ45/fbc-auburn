// Safe to edit by hand
// Splits the church mark (brand/logo/mark.svg) into its 32 bricks for the brick-by-brick build in
// src/components/motion/MarkBuild.astro. The print's red path is one long evenodd path: each
// brick's outline is a large subpath, the white flecks are small ones. We keep only the outlines
// (as clip shapes over the raster print, so the grain still comes from the picture) and put them
// in laying order: bottom course first, working back and forth like a mason, so the cross is
// closed in from below and its top is sealed by the last course.
//
//   npm run gen:mark   (re-run only if brand/logo/mark.svg changes)
import { readFileSync, writeFileSync } from 'node:fs';

const svg = readFileSync('brand/logo/mark.svg', 'utf8');
const viewBox = svg.match(/viewBox="([^"]+)"/)[1];
// The first path is the red brick fill; the second is the dark grain, which the raster carries.
const d = svg.match(/<path[^>]*?d="([^"]+)"/)[1];

const bricks = d
  .split(/(?=M)/)
  .map((sub) => {
    const n = sub.match(/-?\d+(?:\.\d+)?/g).map(Number);
    let x0 = Infinity,
      y0 = Infinity,
      x1 = -Infinity,
      y1 = -Infinity;
    for (let i = 0; i + 1 < n.length; i += 2) {
      x0 = Math.min(x0, n[i]);
      x1 = Math.max(x1, n[i]);
      y0 = Math.min(y0, n[i + 1]);
      y1 = Math.max(y1, n[i + 1]);
    }
    return { sub: sub.trim(), x0, y0, w: x1 - x0, h: y1 - y0 };
  })
  // Bricks are about 100 units tall; flecks are a few units.
  .filter((b) => b.w > 30 && b.h > 30);

if (bricks.length !== 32) throw new Error(`Expected 32 bricks, found ${bricks.length}.`);

// Courses are about 103 units apart; course 0 is the top.
const course = (b) => Math.round((b.y0 - 12) / 103);
const courses = Math.max(...bricks.map(course)) + 1;
const ordered = [];
for (let c = courses - 1, k = 0; c >= 0; c--, k++) {
  const row = bricks.filter((b) => course(b) === c).sort((a, b) => a.x0 - b.x0);
  if (k % 2) row.reverse();
  row.forEach((b) => ordered.push({ ...b, course: k }));
}

// Round the outline to whole units (about half a pixel on screen) to keep the inlined markup small.
const tidy = (s) =>
  s.replace(/-?\d+\.\d+/g, (m) => String(Math.round(Number(m)))).replace(/, /g, ' ');

const out = `// Generated by scripts/gen-mark-bricks.mjs from brand/logo/mark.svg. Do not edit by hand.
// Each brick's outline in laying order (bottom course first); course counts up from the bottom.
export const MARK_VIEWBOX = '${viewBox}';
export const MARK_COURSES = ${courses};
export const MARK_BRICKS: { d: string; course: number }[] = ${JSON.stringify(
  ordered.map((b) => ({ d: tidy(b.sub), course: b.course })),
  null,
  2,
)};
`;
writeFileSync('src/components/motion/mark-bricks.generated.ts', out);
console.log(`Wrote ${ordered.length} bricks in ${courses} courses.`);
